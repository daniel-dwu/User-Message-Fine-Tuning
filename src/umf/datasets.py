"""Data distribution: small files live in git, large ones on the Hugging Face Hub.

``data/manifest.json`` lists every data artifact the experiments read, with its
sha256 and size. Files under ``git_max_bytes`` are committed directly; the rest
are downloaded from a Hub dataset repo on demand. Either way, ``verify`` checks
the bytes on disk against the manifest, so a corrupted or partial download
cannot silently become a training set.

    python -m umf.datasets pull            # fetch every Hub-hosted file
    python -m umf.datasets verify          # hash-check everything present
    python -m umf.datasets manifest        # (maintainers) rebuild hashes
    python -m umf.datasets push            # (maintainers) upload large files

Set ``UMF_HF_DATASET`` to override the Hub repo id.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
MANIFEST = REPO_ROOT / "data" / "manifest.json"
HF_DATASET = os.environ.get("UMF_HF_DATASET", "REPLACE-ME/user-message-fine-tuning-data")
GIT_MAX_BYTES = 20 * 1024 * 1024


def sha256_of(path: Path, chunk: int = 1 << 20) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        while block := f.read(chunk):
            h.update(block)
    return h.hexdigest()


def load_manifest() -> list[dict]:
    if not MANIFEST.exists():
        return []
    return json.loads(MANIFEST.read_text())["files"]


def cmd_manifest(args: argparse.Namespace) -> None:
    """Rebuild hashes for every path listed (keeps the existing `source` notes)."""
    existing = {e["path"]: e for e in load_manifest()}
    paths = args.paths or list(existing)
    entries = []
    for rel in sorted(paths):
        p = REPO_ROOT / rel
        if not p.exists():
            print(f"[manifest] missing on disk, kept as-is: {rel}", file=sys.stderr)
            if rel in existing:
                entries.append(existing[rel])
            continue
        size = p.stat().st_size
        entries.append(
            {
                "path": rel,
                "bytes": size,
                "sha256": sha256_of(p),
                "hosted_on_hub": size > GIT_MAX_BYTES,
                "source": existing.get(rel, {}).get("source", ""),
            }
        )
    MANIFEST.parent.mkdir(parents=True, exist_ok=True)
    MANIFEST.write_text(json.dumps({"hf_dataset": HF_DATASET, "files": entries}, indent=2) + "\n")
    # Keep git and the manifest in agreement: hub-hosted files are ignored by
    # path, everything else is committed.
    hosted = [e["path"] for e in entries if e["hosted_on_hub"]]
    (REPO_ROOT / "data" / ".gitignore").write_text(
        "# Generated by `python -m umf.datasets manifest`. Hub-hosted files.\n"
        + "".join(f"/{Path(h).relative_to('data')}\n" for h in hosted)
    )
    print(f"[manifest] wrote {len(entries)} entries ({len(hosted)} hub-hosted) -> {MANIFEST}")


def cmd_verify(args: argparse.Namespace) -> None:
    bad = missing = ok = 0
    for e in load_manifest():
        p = REPO_ROOT / e["path"]
        if not p.exists():
            missing += 1
            print(f"  missing  {e['path']}" + ("  (run `pull`)" if e["hosted_on_hub"] else ""))
            continue
        if sha256_of(p) != e["sha256"]:
            bad += 1
            print(f"  MISMATCH {e['path']}")
        else:
            ok += 1
    print(f"[verify] ok={ok} missing={missing} mismatched={bad}")
    if bad or (missing and args.strict):
        sys.exit(1)


def cmd_pull(_args: argparse.Namespace) -> None:
    from huggingface_hub import hf_hub_download

    for e in load_manifest():
        if not e["hosted_on_hub"]:
            continue
        p = REPO_ROOT / e["path"]
        if p.exists() and sha256_of(p) == e["sha256"]:
            continue
        print(f"[pull] {e['path']} ({e['bytes'] / 1e6:.0f} MB)")
        got = hf_hub_download(
            repo_id=HF_DATASET,
            repo_type="dataset",
            filename=e["path"],
            local_dir=REPO_ROOT,
        )
        if sha256_of(Path(got)) != e["sha256"]:
            sys.exit(f"[pull] sha256 mismatch after download: {e['path']}")
    print("[pull] done")


def cmd_push(_args: argparse.Namespace) -> None:
    from huggingface_hub import HfApi

    api = HfApi()
    api.create_repo(HF_DATASET, repo_type="dataset", exist_ok=True)
    for e in load_manifest():
        if not e["hosted_on_hub"]:
            continue
        p = REPO_ROOT / e["path"]
        if not p.exists():
            sys.exit(f"[push] missing locally: {e['path']}")
        print(f"[push] {e['path']} ({e['bytes'] / 1e6:.0f} MB)")
        api.upload_file(
            path_or_fileobj=str(p),
            path_in_repo=e["path"],
            repo_id=HF_DATASET,
            repo_type="dataset",
        )
    print("[push] done")


def main() -> None:
    p = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    sub = p.add_subparsers(dest="cmd", required=True)
    m = sub.add_parser("manifest", help="rebuild hashes/sizes for the listed paths")
    m.add_argument("paths", nargs="*", help="repo-relative paths (default: existing entries)")
    m.set_defaults(fn=cmd_manifest)
    v = sub.add_parser("verify", help="hash-check every manifest entry present on disk")
    v.add_argument("--strict", action="store_true", help="also fail on missing files")
    v.set_defaults(fn=cmd_verify)
    sub.add_parser("pull", help="download Hub-hosted files").set_defaults(fn=cmd_pull)
    sub.add_parser("push", help="upload Hub-hosted files (maintainers)").set_defaults(fn=cmd_push)
    args = p.parse_args()
    args.fn(args)


if __name__ == "__main__":
    main()
